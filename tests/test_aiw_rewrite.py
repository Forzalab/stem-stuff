"""P4.1c: one-pass LLM rewrite of detector-flagged strings (aiw_rewrite.py).

No network, no serve.py: the LLM is a fake callable and the detector is a lookup
over tests/fixtures/aiw_rewrite_js.json, generated by the upstream JS
analyzeText() (conorbronsdon/avoid-ai-writing@013d1db detector/patterns.js).
"""

import hashlib
import json
import os
import statistics
import sys
import unittest

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

import aiw_rewrite as R  # noqa: E402

with open(os.path.join(ROOT, "tests", "fixtures", "aiw_rewrite_js.json"), encoding="utf-8") as fh:
    JS = {c["text"]: c["issues"] for c in json.load(fh)["cases"]}


def detect(text):
    """JS detector output for known strings; unknown strings fail closed (flagged)."""
    return JS.get(text, [{"type": "unknown-to-fixture", "text": text}])


def item(i, text, **kw):
    return {"id": str(i), "text": text, "issues": JS[text], **kw}


class FakeLLM:
    def __init__(self, reply):
        self.reply, self.calls = reply, []

    def __call__(self, system, user):
        self.calls.append((system, user))
        return self.reply if isinstance(self.reply, str) else json.dumps(self.reply)


MOREOVER = "Moreover, the edge A-B has weight 4 and C-D has weight 7."
SHORTCUT = "It is not just a shortcut, it is a testament to how Dijkstra relaxes $d(v)$ in 3 steps."
ROBUST = "Additionally, this robust method uses `dist[v]` to find the shortest path in 12 ms."
HOPE = "I hope this helps! The answer is $x = 5$ m/s."
EXPERTS = "Experts say the greedy pick from A is always safe."
DELVE = "Great question! Let's delve into how BFS visits node A first."
HEDGE = "This could potentially reduce the cut to 9 edges in the graph."
ORDER = "In order to find the flow, push 5 units along A-C."
SEAMLESS = "Furthermore, the seamless update sets $d(B) = 4$ in 2 ms."
STUDIES = "Studies show that Prim's method is a game-changer for 10 nodes."
TODAY = "In today's world, graphs are a pivotal tool for routing 1,200 packets."
NOTING = "It's worth noting that node C has degree 3 in this graph."


class VendoredSource(unittest.TestCase):
    def test_patterns_pinned(self):
        with open(R.PATTERNS_PATH, "rb") as fh:
            self.assertEqual(hashlib.sha256(fh.read()).hexdigest(), R.PATTERNS_SHA256)

    def test_every_mapped_section_exists(self):
        sections = R.load_sections()
        for t, (heading, sel) in R.TYPE_SECTIONS.items():
            self.assertIn(heading, sections, t)
            self.assertTrue(R.rule_block(t, [{"type": t, "text": "x"}], 70), t)

    def test_editorial_cards_dropped(self):
        self.assertNotIn("Editorial decision card", "".join(R.load_sections().values()))


class Prompt(unittest.TestCase):
    def test_only_matching_rule_blocks(self):
        system, user = R.build_prompt([item(1, MOREOVER), item(2, EXPERTS)])
        self.assertIn("### Transition phrases to remove or rewrite", system)
        self.assertIn("### Vague attributions", system)
        self.assertIn('"Moreover" / "Furthermore"', system)
        self.assertIn("Studies show", system)  # the vague-attribution rule text itself
        heads = [ln for ln in system.split("\n") if ln.startswith("### ")]
        self.assertEqual(len(heads), 2, heads)
        for absent in ("Chatbot artifacts", "Sycophantic tone", "Words and phrases", "Sentence structure", "Hedge-stacked"):
            self.assertNotIn(absent, system)
        self.assertNotIn("Editorial decision card", system)

    def test_vocab_injects_only_flagged_rows(self):
        system, _ = R.build_prompt([item(1, ROBUST)])
        self.assertIn('"robust" → strong, reliable, solid', system)
        self.assertNotIn("tapestry", system)
        self.assertNotIn("delve", system)

    def test_bullet_selector_picks_the_frame(self):
        system, _ = R.build_prompt([item(1, SHORTCUT)])
        self.assertIn("Rewrite as a direct positive statement", system)
        self.assertNotIn("Compulsive rule of three", system)  # same section, other bullet
        self.assertIn('"testament to" → shows, proves, demonstrates', system)

    def test_copy_rules_cap_and_batch(self):
        items = [item(1, MOREOVER), item(2, HOPE, max_len=40), item(3, DELVE)]
        system, user = R.build_prompt(items)
        for rule in ("Sentence case", "No praise", 'no "!"', "max characters"):
            self.assertIn(rule, system)
        payload = json.loads(user)["strings"]
        self.assertEqual([s["id"] for s in payload], ["1", "2", "3"])
        self.assertEqual(payload[0]["max"], 65)       # default STYLE cap
        self.assertEqual(payload[1]["max"], 40)       # the string's own cap
        self.assertIn("JSON only", system)

    def test_token_budget_and_median(self):
        texts = [t for t, iss in JS.items() if iss]
        views = [texts[i:i + 3] for i in range(0, len(texts), 3)] + [texts]  # 3-string views + one 13-string view
        toks = []
        for v in views:
            s, u = R.build_prompt([item(k, t) for k, t in enumerate(v)])
            toks.append(R.estimate_tokens(s) + R.estimate_tokens(u))
        self.assertLessEqual(max(toks), R.TOKEN_BUDGET, toks)
        self.assertLess(statistics.median(toks), 800, toks)
        print(f"\naiw_rewrite prompt tokens per view {toks}, median {statistics.median(toks)}", file=sys.stderr)

    def test_over_budget_shrinks_blocks(self):
        items = [item(1, SHORTCUT)]
        big_s, _ = R.build_prompt(items)
        small_s, u = R.build_prompt(items, budget=300)
        self.assertLess(len(small_s), len(big_s))
        self.assertIn("### Sentence structure", small_s)

    def test_one_call_per_view(self):
        llm = FakeLLM({})
        R.rewrite_view([item(1, MOREOVER), item(2, ROBUST), item(3, HOPE),
                        {"id": "4", "text": "Visit A, then B, then C.", "issues": []}], llm, detect)
        self.assertEqual(len(llm.calls), 1)
        self.assertNotIn("Visit A, then B", llm.calls[0][1])  # clean strings are not sent

    def test_nothing_flagged_no_call(self):
        llm = FakeLLM({})
        out = R.rewrite_view([{"id": "a", "text": "B is new.", "issues": []}], llm, detect)
        self.assertEqual(llm.calls, [])
        self.assertEqual(out["texts"], {"a": "B is new."})


class Guard(unittest.TestCase):
    def test_changed_number(self):
        self.assertTrue(R.preservation_errors(MOREOVER, "The edge A-B has weight 5 and C-D has weight 7."))

    def test_dropped_number(self):
        self.assertIn("number-missing:1,200", R.preservation_errors(TODAY, "Graphs route packets."))

    def test_changed_label(self):
        errs = R.preservation_errors(MOREOVER, "The edge A-E has weight 4 and C-D has weight 7.")
        self.assertIn("label-missing:B", errs)
        self.assertIn("label-added:E", errs)

    def test_changed_latex(self):
        errs = R.preservation_errors(SHORTCUT, "Dijkstra relaxes $d(u)$ in 3 steps.")
        self.assertTrue(any(e.startswith("latex-missing") for e in errs), errs)

    def test_latex_unwrapped(self):
        errs = R.preservation_errors(HOPE, "The answer is x = 5 m/s.")
        self.assertTrue(any(e.startswith("latex-missing") for e in errs), errs)

    def test_code_span(self):
        self.assertTrue(R.preservation_errors(ROBUST, "This method uses dist[v] to find the shortest path in 12 ms."))

    def test_unit(self):
        errs = R.preservation_errors(SEAMLESS, "The update sets $d(B) = 4$ in 2 s.")
        self.assertIn("unit-missing:2 ms", errs)

    def test_variable(self):
        self.assertIn("variable-missing:k", R.preservation_errors("Pick k edges from A.", "Pick n edges from A."))

    def test_clean_rewrites_pass(self):
        pairs = [(MOREOVER, "The edge A-B has weight 4 and C-D has weight 7."),
                 (SHORTCUT, "Dijkstra relaxes $d(v)$ in 3 steps."),
                 (ROBUST, "This method uses `dist[v]` to find the shortest path in 12 ms."),
                 (HOPE, "The answer is $x = 5$ m/s."),
                 (DELVE, "BFS visits node A first."),
                 (EXPERTS, "The greedy pick from A is safe here."),
                 (NOTING, "Node C has degree 3 in this graph."),
                 (ORDER, "To find the flow, push 5 units along A-C.")]
        for a, b in pairs:
            self.assertEqual(R.preservation_errors(a, b), [], (a, b))

    def test_sentence_initial_article_is_not_a_label(self):
        self.assertEqual(R.preservation_errors("A path from B to C exists.", "The path from B to C exists."), [])


class OnePass(unittest.TestCase):
    def run_view(self, reply, items):
        llm = FakeLLM(reply)
        return R.rewrite_view(items, llm, detect), llm

    def test_happy_path(self):
        items = [item(1, MOREOVER), item(2, SHORTCUT), item(3, ROBUST)]
        out, _ = self.run_view({"1": "The edge A-B has weight 4 and C-D has weight 7.",
                                "2": "Dijkstra relaxes $d(v)$ in 3 steps.",
                                "3": "This method uses `dist[v]` to find the shortest path in 12 ms."}, items)
        self.assertEqual(out["texts"]["2"], "Dijkstra relaxes $d(v)$ in 3 steps.")
        self.assertTrue(all(e["status"] == "rewritten" for e in out["log"]), out["log"])
        self.assertGreater(out["prompt_tokens"], 0)

    def test_guard_failure_keeps_original_or_fallback(self):
        items = [item(1, MOREOVER), item(2, SEAMLESS, fallback="The update sets $d(B) = 4$.")]
        out, _ = self.run_view({"1": "The edge A-B has weight 5 and C-D has weight 7.",
                                "2": "The update sets $d(B) = 3$ in 2 ms."}, items)
        self.assertEqual(out["texts"]["1"], MOREOVER)
        self.assertEqual(out["texts"]["2"], "The update sets $d(B) = 4$.")
        self.assertTrue(all(e["reason"].startswith("preservation:") for e in out["log"]), out["log"])

    def test_still_flagged_gives_up_after_one_pass(self):
        items = [item(1, MOREOVER)]
        out, llm = self.run_view({"1": "Moreover, edge A-B has weight 4 and C-D has weight 7."}, items)
        self.assertEqual(len(llm.calls), 1)                    # no second ask
        self.assertEqual(out["texts"]["1"], MOREOVER)
        self.assertEqual(out["log"][0]["reason"], "still-flagged:transition")

    def test_bad_json_keeps_all_originals(self):
        items = [item(1, MOREOVER), item(2, HOPE, fallback="The answer is $x = 5$ m/s.")]
        for reply in ("Sure! Here are the rewrites.", "{not json", "[\"a\", \"b\"]", ""):
            out, llm = self.run_view(reply, items)
            self.assertEqual(out["texts"], {"1": MOREOVER, "2": "The answer is $x = 5$ m/s."}, reply)
            self.assertEqual({e["reason"] for e in out["log"]}, {"bad-json"})
            self.assertEqual(len(llm.calls), 1)

    def test_fenced_json_accepted(self):
        out, _ = self.run_view('```json\n{"1": "BFS visits node A first."}\n```', [item(1, DELVE)])
        self.assertEqual(out["texts"]["1"], "BFS visits node A first.")

    def test_missing_id_too_long_exclaim(self):
        items = [item(1, MOREOVER), item(2, HEDGE, max_len=30), item(3, EXPERTS)]
        out, _ = self.run_view({"2": "This could reduce the cut to 9 edges in the graph.",
                                "3": "The greedy pick from A is safe!"}, items)
        reasons = {e["id"]: e["reason"] for e in out["log"]}
        self.assertEqual(reasons["1"], "missing")
        self.assertTrue(reasons["2"].startswith("too-long"))
        self.assertEqual(reasons["3"], "copy:exclamation")
        self.assertEqual(out["texts"], {"1": MOREOVER, "2": HEDGE, "3": EXPERTS})

    def test_llm_error_keeps_originals(self):
        def boom(system, user):
            raise TimeoutError("slow")
        out = R.rewrite_view([item(1, MOREOVER)], boom, detect)
        self.assertEqual(out["texts"], {"1": MOREOVER})
        self.assertEqual(out["log"][0]["reason"], "llm-error:TimeoutError")

    def test_no_detector_fails_closed(self):
        out = R.rewrite_view([item(1, DELVE)], FakeLLM({"1": "BFS visits node A first."}), detect=None) \
            if R._default_detect() is None else None
        if out is not None:
            self.assertEqual(out["texts"]["1"], DELVE)
            self.assertEqual(out["log"][0]["reason"], "no-detector")


if __name__ == "__main__":
    unittest.main()
